"""Functions to help determine stimulus alignment
"""
import os
import datetime
from collections import defaultdict

import numpy as np
import wavio
from scipy.signal import correlate

from soundsig.signal import resample_signal


def _find_alignment(signal, template):
    """Find best index in signal to align template waveform
    """
    correlated = correlate(signal, template, mode="same")
    peak = np.argmax(np.abs(correlated))
    return correlated, peak - len(template) // 2


def compute_realigned_trial_times(
        playback_df: 'pd.DataFrame',
        intan_start_time: 'datetime.datetime',
        mic_reader: 'format.wav.AudioFile',
        playback_channels: 'Optional[Union[int, List[int]]]' = None,
        window: 'int' = 1.0
    ):
    """Estimate trial start times (relative to start of intan file)

    In some of our setups, we have pyoperant send a digital code to the intan board, to align
    trials to the exact sample of the ephys data. However, if these pulses are missing for whatever
    reason, then you need this function: to find the best possible alignment of stimulus playbacks
    using the correlation with microphone data.

    The following timestamps are used to find approximate values. Note that since the intan file timestamp
    only has 1s resolution, we need to correlate the sound signal to find the best match possible. The channel
    or channels which should be checked for playback audio can be specified.

        Intan file start time: computer timestamp taken from the intan rhd filename (accurate to 1s)
        Stimulus start times: computer timestamp of each trial (generated by pyoperant)

    Each trial is aligned independently of the others, with freedom to slide up to `window` seconds from
    the estimated best alignment.

    Parameters
    ----------
    playback_df : pandas.DataFrame
        Dataframe generated from the pyoperant csv file(s), each row is one trial.
        Must have columns
            'stimulus_name' (local path to stimulus file)
            'time' (trial timestamp)
            'duration' (duration of stimulus in seconds)
    intan_start_time : datetime.datetime
        Datetime estimate of the Intan start time. Used as a starting point
        for alignment (get this from the RHD filename if no better source)
    mic_reader : format.wav.AudioFile
        Data reader for microphone data
    playback_channel : int or List[int]
        Integer or list of integers of channels in the `mic_reader` object to correlate with stimulus
        audio. Use this when only one or more channels are expected to have the most relevant audio data
        to match with playbacks
    window : float
        Half-width of window (in seconds) to look for alignment peak. Typically this should be <= the
        inter-trial interval so there is not bleed through in the window used for correlation

    Returns
    -------
    An array of floating point numbers with same length as playback_df, where
    the nth value is the start time for the nth trial in seconds from start
    of Intan recording.
    """
    new_start_times = []
    shifts = []
    if playback_channels is None:
        playback_channels = list(range(mic_reader.channels))
    elif isinstance(playback_channels, int):
        playback_channels = [playback_channels]
    else:
        playback_channels = list(playback_channels)

    intan_sr = mic_reader.sampling_rate

    _loaded_stim_cache = {}
    for row_idx, row in playback_df.iterrows():
        # Resample the stimulus playback file to the intan recording rate
        if row.stimulus_name in _loaded_stim_cache:
            wav_data = _loaded_stim_cache[row.stimulus_name]
        else:
            wav_object = wavio.read(row.stimulus_name)

            stim_sr = wav_object.rate
            wav_data = wav_object.data[:, 0]
            if stim_sr != intan_sr:
                _, wav_data  = resample_signal(wav_data, stim_sr, intan_sr)
            _loaded_stim_cache[row.stimulus_name] = wav_data

        # Estimate the start time by relating the timestamp in the csv to the timestamp in the rhd filename
        estimated_start = (row.time - intan_start_time).total_seconds()

        # If the estimate doesnt make sense... just use the estimate based on timestamp
        if estimated_start < 0 or estimated_start > mic_reader.frames / mic_reader.sampling_rate:
            new_start_times.append(estimated_start)
            shifts.append(0.0)
            continue

        # Get the microphone data
        recorded_data = mic_reader.time_slice(
            estimated_start - window,
            estimated_start + row.duration + window
        ).data
        recorded_data = recorded_data - np.mean(recorded_data, axis=0)

        best_score = 0
        best_estimate_index = None

        for ch in playback_channels:
            correlated, estimated_index = _find_alignment(recorded_data[:, ch], wav_data)
            score = np.max(np.abs(correlated) / np.max(np.abs(recorded_data[:, ch])))
            if np.max(np.abs(recorded_data[:, ch])) == 0:
                # This probably means that the data is corrupted - the microphones were off
                # or the signal didnt make it into the system. Here we probably can't do much better than
                # using the approximate start time with the average of the data we've seen before
                print("(!) WARNING while computing playback codes: mic data appears corrupted in time window {} to {}".format(
                    estimated_start - window,
                    estimated_start + row.duration + window
                ))
                best_estimate_index = estimated_start + (np.mean(shifts) if len(shifts) else 0)

            if score > best_score:
                best_estimate_index = estimated_index

        estimate_after_correlation = (estimated_start - window) + best_estimate_index / intan_sr

        new_start_times.append(estimate_after_correlation)
        shifts.append(new_start_times[-1] - estimated_start)

    # If any shifts were greater than 100ms away from the median, they are suspicious and replace them with the median shift
    shifts = np.array(shifts)
    median_shift = np.median(shifts)
    new_start_times = np.array(new_start_times)

    suspisciously_bad_shifts = np.abs(shifts - median_shift) > 0.2

    if np.any(suspisciously_bad_shifts):
        print("Warning: {} shifts were found that were more than 100ms away from the median shift. Replacing them with median".format(np.sum(suspisciously_bad_shifts)))
        new_start_times[suspisciously_bad_shifts] = new_start_times[suspisciously_bad_shifts] - shifts[suspisciously_bad_shifts] + median_shift

    diffs = np.diff(new_start_times)
    if any(diffs < 0.0):
        bad_trials = np.where(diffs < 0.0)[0]
        error_strings = []
        for bad_trial in bad_trials:
            error_strings.append("Row {} to {}: start times estimated to be {:.5f} and {:.5f}".format(
                bad_trial,
                bad_trial + 1,
                new_start_times[bad_trial],
                new_start_times[bad_trial + 1]
            ))
        raise Exception("Start time of trial cannot be before the start time of the previous trial:\n{}".format("\n".join(error_strings)))
   
    print("Offsetting playbacks by best correlation\n"
            "On average, shifted by {:.2f}".format(np.mean(shifts)))

    return new_start_times


def _calculate_playback_repetitions(playbacks_df):
    """Compute the repetition number for each stimulus

    Parameters
    ----------
    playbacks_df : pandas.DataFrame
        DataFrame with column 'stimulus_name' as a unique identifier (e.g.
        file path) for each trial

    Returns
    -------
    A numpy array of integers of the same length as playbacks_df, where
    the nth entry is the repetition number for the nth trial.
    """
    repetition = []

    counts = defaultdict(int)
    for i, row in playbacks_df.iterrows():
        repetition.append(counts[row.stimulus_name])
        counts[row.stimulus_name] += 1

    return np.array(repetition)


def create_replacement_codes(playbacks_df, trial_times, sampling_rate, max_time):
    """Generate an list of codes mimicing the digital codes sent by pyoperant

    Mimics the format output by
    preprocess.sound.playback_utils.convert_digital_to_metadata

    Parameters
    ----------
    playback_df : pandas.DataFrame
        Dataframe generated from the pyoperant csv file(s), each row is one trial.
        Must have columns 'stimulus_name' (local path to stimulus file),
        'duration' (stimulus length in seconds), and 'trial' (integer trial #)
    trial_times : array
        Array of floats for trial start times (probably produced by
        _calculate_playback_repetitions)
    sampling_rate : float
        Sampling rate of data
    max_time : float
        Maximum time (in seconds) of Intan data file. Function will exclude
        codes for trials starting before 0 or ending after max_time

    Returns
    -------
    A list of dictionaries, where each dictionary has the keys 'action',
    'object', 'repetition', and 'trial'
    """
    repetition = _calculate_playback_repetitions(playbacks_df)

    codes = []
    for i, row in playbacks_df.iterrows():
        if trial_times[i] < 0 or trial_times[i] + row.duration > max_time:
            continue

        codes.append((
            int(trial_times[i] * sampling_rate),
            {
                "action": "queu",
                "object": "Spea",
                "repetition": repetition[i],
                "trial": row.trial
            }
        ))

    return codes
